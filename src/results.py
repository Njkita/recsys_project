"""Aggregate every `runs/<exp>/result.json` into a single comparison table.

Outputs:
- `runs/results.csv` — wide table, one row per experiment
- `runs/results.md`  — markdown leaderboard sorted by NDCG@10 (test)
- prints same to stdout

Run: `python -m src.results [--runs-dir runs] [--out runs]`
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Any, Dict, List


COLS = [
    "exp_name", "model", "n_blocks", "d", "loss", "n_neg",
    "best_epoch", "val_NDCG@10",
    "test_HR@5", "test_HR@10", "test_HR@20",
    "test_NDCG@5", "test_NDCG@10", "test_NDCG@20", "test_MRR@20",
    "params_total", "device", "config_path",
]


def collect(runs_dir: Path) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    for result_path in sorted(runs_dir.rglob("result.json")):
        try:
            data = json.loads(result_path.read_text())
        except Exception as e:                                      # noqa: BLE001
            print(f"[results] failed to read {result_path}: {e}")
            continue
        tm = data.get("test_metrics", {}) or {}
        # MRR@K key depends on the max ks used; pull whichever is present.
        mrr_val = float("nan")
        for k in (20, 10, 5):
            if f"MRR@{k}" in tm:
                mrr_val = tm[f"MRR@{k}"]
                break
        row = {
            "exp_name": data.get("exp_name", result_path.parent.name),
            "model": data.get("model", "?"),
            "n_blocks": data.get("n_blocks", "?"),
            "d": data.get("d", "?"),
            "loss": data.get("loss", "?"),
            "n_neg": data.get("n_neg", "?"),
            "best_epoch": data.get("best_epoch", -1),
            "val_NDCG@10": data.get("val_NDCG@10", float("nan")),
            "test_HR@5": tm.get("HR@5", float("nan")),
            "test_HR@10": tm.get("HR@10", float("nan")),
            "test_HR@20": tm.get("HR@20", float("nan")),
            "test_NDCG@5": tm.get("NDCG@5", float("nan")),
            "test_NDCG@10": tm.get("NDCG@10", float("nan")),
            "test_NDCG@20": tm.get("NDCG@20", float("nan")),
            "test_MRR@20": mrr_val,
            "params_total": (data.get("params") or {}).get("total", -1),
            "device": data.get("device", "?"),
            "config_path": data.get("config_path", "?"),
        }
        rows.append(row)
    return rows


def write_csv(rows: List[Dict[str, Any]], out_path: Path) -> None:
    with out_path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLS)
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k, "") for k in COLS})


def render_markdown(rows: List[Dict[str, Any]]) -> str:
    if not rows:
        return "_no completed experiments yet_\n"
    rows_sorted = sorted(
        rows,
        key=lambda r: (r.get("test_NDCG@10") if isinstance(r.get("test_NDCG@10"), (int, float)) else -1),
        reverse=True,
    )

    def cell(v: Any) -> str:
        if isinstance(v, float):
            return f"{v:.4f}" if v == v else "-"  # nan check
        return str(v)

    keep_cols = [
        "exp_name", "model", "n_blocks", "d", "loss",
        "test_HR@10", "test_NDCG@10", "test_MRR@20",
        "val_NDCG@10", "best_epoch", "params_total",
    ]
    head = "| " + " | ".join(keep_cols) + " |\n"
    sep = "| " + " | ".join(["---"] * len(keep_cols)) + " |\n"
    body = ""
    for r in rows_sorted:
        body += "| " + " | ".join(cell(r.get(c, "")) for c in keep_cols) + " |\n"
    return head + sep + body


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--runs-dir", default="runs", type=str)
    p.add_argument("--out", default="runs", type=str)
    args = p.parse_args()

    runs_dir = Path(args.runs_dir).resolve()
    out_dir = Path(args.out).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    rows = collect(runs_dir)
    csv_path = out_dir / "results.csv"
    md_path = out_dir / "results.md"
    write_csv(rows, csv_path)
    md = render_markdown(rows)
    md_path.write_text(
        "# Results — sequential recommenders on ML-20M\n\n"
        "Full-catalog leave-one-out, filter-seen, NDCG/HR/MRR over the entire "
        "catalog. Generated by `python -m src.results`.\n\n"
        + md,
        encoding="utf-8",
    )
    print(md)
    print(f"[results] {len(rows)} experiment(s) → {csv_path}, {md_path}")


if __name__ == "__main__":
    main()
